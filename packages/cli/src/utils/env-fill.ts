/**
 * @fileoverview App-secret filling for env files (`.env`, `.env.docker`).
 *
 * The go-live story: `ignex ship` turns the secret placeholders the scaffold
 * and ops templates emit into real generated values — without ever touching a
 * value the operator already set. Secret variables are discovered from the
 * project's `src/config/env.ts` schema (`metadata.secret`, the
 * `@ignex/core/env` contract); the target file is patched line-wise; only
 * empty values (`KEY=`, `KEY=""`, or a commented `# KEY=` placeholder) are
 * filled. Pure line functions are exported separately from the IO wrappers so
 * tests and `--dry-run` paths can run without a filesystem.
 */
import { join } from "node:path";
import { pathToFileURL } from "node:url";
import { ENV_CONFIG_PATH } from "./env-check.js";
import { exists, readTextFile, writeFileEnsuringDir } from "./fs.js";
import { generateHexSecret } from "./secrets.js";

/** One secret to write: the env var name and its generated value. */
export interface SecretAssignment {
  /** Env var name (e.g. `SESSION_SECRET`). */
  readonly key: string;
  /** Generated value, safe to embed unquoted (base64url or hex). */
  readonly value: string;
}

/** Outcome of a pure fill pass over env-file lines. */
export interface FillResult {
  /** Keys that got a value written (placeholder filled or appended). */
  readonly filled: readonly string[];
  /** Keys that already had a value and were left untouched. */
  readonly kept: readonly string[];
}

/** Matches an active dotenv assignment: optional `export`, `KEY=value`. */
const ASSIGN_RE = /^\s*(?:export\s+)?([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*?)\s*$/;
/** Marker above keys appended by a fill pass (written once, at the end). */
const GENERATED_MARKER = "# generated by ignex — do not commit real secrets";

/** True when a raw value counts as "still empty" (``, `""`, `''). */
const isEmptyValue = (raw: string): boolean =>
  raw.trim() === "" || raw.trim() === '""' || raw.trim() === "''";

/**
 * Parse env-file lines into a `key → raw value` map. Later assignments win
 * (dotenv semantics); commented lines are ignored.
 *
 * @param lines - The file's lines (no trailing newline).
 * @returns The assignment map, in first-seen key order.
 */
export function parseEnvAssignments(lines: readonly string[]): Map<string, string> {
  const map = new Map<string, string>();
  for (const line of lines) {
    const match = ASSIGN_RE.exec(line);
    if (match !== null) {
      const key = match[1];
      if (key !== undefined) map.set(key, match[2] ?? "");
    }
  }
  return map;
}

/**
 * Secret keys that still need a value: absent from the file, present but
 * empty, or present only as a commented `# KEY=` placeholder.
 *
 * @param lines - The env file's lines.
 * @param keys - Secret var names from the project's env schema.
 * @returns The subset of `keys` a fill pass would write.
 */
export function unfilledSecretKeys(lines: readonly string[], keys: readonly string[]): string[] {
  const active = parseEnvAssignments(lines);
  return keys.filter((key) => {
    const value = active.get(key);
    return value === undefined || isEmptyValue(value);
  });
}

/**
 * Patch env-file lines with secret values. Only empty active assignments and
 * commented placeholders are written; keys absent from the file are appended
 * under a {@link GENERATED_MARKER} comment (added once).
 *
 * @param lines - The env file's lines (no trailing newline).
 * @param assignments - The secrets to write.
 * @returns The patched lines plus which keys were filled vs kept.
 */
export function applySecrets(
  lines: readonly string[],
  assignments: readonly SecretAssignment[],
): { lines: string[]; filled: string[]; kept: string[] } {
  const filled: string[] = [];
  const kept: string[] = [];
  const pending: SecretAssignment[] = [];
  const output = [...lines];

  for (const assignment of assignments) {
    const key = assignment.key;
    const escaped = key.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    const lineRe = new RegExp(`^(\\s*(?:export\\s+)?${escaped}\\s*=\\s*)(.*)$`);

    let wrote = false;
    for (let i = output.length - 1; i >= 0; i -= 1) {
      const match = lineRe.exec(output[i] ?? "");
      const prefix = match?.[1];
      if (!match || prefix === undefined) continue;
      if (isEmptyValue(match[2] ?? "")) {
        output[i] = `${prefix}${assignment.value}`;
        filled.push(key);
      } else {
        kept.push(key);
      }
      wrote = true;
      break;
    }
    if (wrote) continue;

    // No active assignment — fill a commented placeholder if the template
    // left one (`# SESSION_SECRET=`), else queue for appending.
    const placeholderRe = new RegExp(`^\\s*#\\s*${escaped}\\s*=\\s*$`);
    let placed = false;
    for (let i = output.length - 1; i >= 0; i -= 1) {
      if (placeholderRe.test(output[i] ?? "")) {
        output[i] = `${key}=${assignment.value}`;
        filled.push(key);
        placed = true;
        break;
      }
    }
    if (!placed) pending.push(assignment);
  }

  if (pending.length > 0) {
    const last = output[output.length - 1];
    if (last !== undefined && last.trim() !== "") output.push("");
    output.push(GENERATED_MARKER);
    for (const assignment of pending) {
      output.push(`${assignment.key}=${assignment.value}`);
      filled.push(assignment.key);
    }
  }

  return { lines: output, filled, kept };
}

/**
 * Secret variable names declared in the project's env schema.
 *
 * Loads `src/config/env.ts` (cache-busted, like {@link checkProjectEnv}) and
 * reads `metadata.secret` off each property. When the module throws on import
 * — typically a missing required var, exactly when filling matters most — it
 * falls back to a conservative source scan for the canonical
 * `KEY: Type.Optional(Type.String({ metadata: { secret: true } }))` shapes.
 *
 * @param root - Project root directory.
 * @returns Secret var names in declaration order; empty without an env module.
 */
export async function listSecretVars(root: string): Promise<string[]> {
  const envPath = join(root, ENV_CONFIG_PATH);
  if (!(await exists(envPath))) return [];
  try {
    const url = `${pathToFileURL(envPath).href}?t=${Date.now()}`;
    const mod = (await import(url)) as {
      envSchema?: { properties?: Record<string, unknown> };
      schema?: { properties?: Record<string, unknown> };
    };
    const schema = mod.envSchema ?? mod.schema;
    const props = schema?.properties;
    if (!props || typeof props !== "object") return [];
    return Object.entries(props)
      .filter(
        ([, prop]) => (prop as { metadata?: { secret?: unknown } })?.metadata?.secret === true,
      )
      .map(([key]) => key);
  } catch {
    return scanSecretVars(await readTextFile(envPath));
  }
}

/**
 * Fallback secret scan over env-config source text (used when the module
 * cannot be imported). Conservative: only the canonical inline
 * `metadata: { secret: true }` shape is recognized.
 *
 * @param source - The `src/config/env.ts` source text.
 * @returns Declared secret var names, in order of first appearance.
 */
export function scanSecretVars(source: string): string[] {
  const names: string[] = [];
  const re =
    /\b([A-Za-z_][A-Za-z0-9_]*)\s*:\s*Type\.(?:Optional\()?Type\.\w+\([^)]*?metadata:\s*\{\s*secret:\s*true/gs;
  for (const match of source.matchAll(re)) {
    const name = match[1];
    if (name !== undefined && !names.includes(name)) names.push(name);
  }
  return names;
}

/**
 * Fill the project's secret vars in one env file, in place.
 *
 * Never overwrites non-empty values, never creates the file when missing, and
 * writes nothing when no secrets end up filled.
 *
 * @param root - Project root directory.
 * @param file - Env file path relative to the root (e.g. `.env`).
 * @param generate - Value factory per key (default: 32-byte hex, the
 *   `openssl rand -hex 32` shape).
 * @returns The fill outcome, or null when the file does not exist.
 */
export async function fillEnvSecrets(
  root: string,
  file: string,
  generate: (key: string) => string = () => generateHexSecret(),
): Promise<FillResult | null> {
  const path = join(root, file);
  if (!(await exists(path))) return null;

  const keys = await listSecretVars(root);
  if (keys.length === 0) return { filled: [], kept: [] };

  const text = await readTextFile(path);
  const assignments = keys.map((key) => ({ key, value: generate(key) }));
  const result = applySecrets(
    text.replace(/\r\n/g, "\n").replace(/\n$/, "").split("\n"),
    assignments,
  );

  if (result.filled.length > 0) {
    await writeFileEnsuringDir(path, `${result.lines.join("\n")}\n`);
  }
  return { filled: result.filled, kept: result.kept };
}
