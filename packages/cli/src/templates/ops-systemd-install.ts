/**
 * @fileoverview `ignex ops systemd` host-install template — `deploy/install.sh`,
 * the idempotent one-shot that turns the generated `deploy/` artifacts into a
 * running service: system user, unit installation, enable (and start when a
 * build is already present), optional Caddyfile placement with backup.
 *
 * Split from `ops-systemd.ts` to keep both under the size gate. Pure
 * function, string in → string out (same convention as the other `ops-*.ts`
 * templates).
 */

export interface SystemdInstallOptions {
  /** Service/unit name (also the default system user). */
  name: string;
  /** The system user the service runs as. */
  user: string;
  /** Absolute path of the deployed checkout. */
  appDir: string;
  /** Local port the app serves on (health polling). */
  port: number;
  /** Liveness path polled after start (framework contract: /health). */
  healthPath: string;
  /** Public domain — used only for the DNS reminder when installing Caddy. */
  domain: string;
}

/**
 * The sudo host-install script: create the system user → chown the checkout →
 * install + enable the units → start when a build already exists (otherwise
 * point at `deploy/deploy.sh`) → optionally install the Caddyfile. Re-runs
 * skip completed steps; `--dry-run` prints every mutation first.
 */
export function systemdInstallTemplate(options: SystemdInstallOptions): string {
  const { name, user, appDir, port, healthPath, domain } = options;
  return `#!/usr/bin/env bash
# install.sh — one-shot host install for ${name}. Generated by \`ignex ops systemd\`.
#
#   sudo deploy/install.sh              # user + units + enable (+ start if built)
#   sudo deploy/install.sh --caddy      # also install ./Caddyfile into /etc/caddy
#   sudo deploy/install.sh --dry-run    # print every mutation first
#
# Idempotent — safe to re-run. When .ignex/server.js is not built yet the
# service is enabled but not started; \`sudo deploy/deploy.sh\` does the first
# build → start → health-verify.
set -euo pipefail

SERVICE="${name}"
APP_USER="${user}"
APP_DIR="${appDir}"
HEALTH_URL="http://127.0.0.1:${port}${healthPath}"
CADDY=0 DRY_RUN=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --caddy) CADDY=1 ;;
    --dry-run) DRY_RUN=1 ;;
    -h|--help) grep '^#' "$0" | head -n 8; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 1 ;;
  esac
  shift
done

require_root() { [[ "$(id -u)" == 0 ]] || { echo "error: run with sudo" >&2; exit 1; }; }
run() {
  if [[ "$DRY_RUN" == 1 ]]; then printf '    + %s\\n' "$*"; return 0; fi
  "$@"
}
step() { printf '\\n==> %s\\n' "$*"; }
info() { printf '    %s\\n' "$*"; }
warn() { printf '    warning: %s\\n' "$*" >&2; }
wait_for_http() {
  local start=$SECONDS
  while :; do
    if curl -fsS --max-time 5 "$HEALTH_URL" >/dev/null 2>&1; then return 0; fi
    if (( SECONDS - start >= 60 )); then return 1; fi
    sleep 2
  done
}

require_root
cd "$APP_DIR"
[[ -f "deploy/$SERVICE.service" ]] || {
  echo "error: deploy/$SERVICE.service not found — run: bunx ignex ops systemd" >&2
  exit 1
}
if [[ "$DRY_RUN" == 1 ]]; then echo "    (dry run — nothing will be changed)"; fi

step "Ensuring system user $APP_USER"
if id -u "$APP_USER" >/dev/null 2>&1; then
  info "user exists"
else
  run groupadd --system "$APP_USER"
  run useradd --system --gid "$APP_USER" --home-dir "$APP_DIR" --no-create-home --shell /usr/sbin/nologin "$APP_USER"
fi

step "Fixing ownership ($APP_USER over $APP_DIR)"
run chown -R "$APP_USER:$APP_USER" "$APP_DIR"

step "Installing units"
run cp -f deploy/*.service /etc/systemd/system/
run systemctl daemon-reload
for unit in deploy/*.service; do
  run systemctl enable "$(basename "$unit")"
done

if [[ -f .ignex/server.js ]]; then
  step "Starting $SERVICE (build present)"
  run systemctl restart "$SERVICE"
  if [[ "$DRY_RUN" == 1 ]]; then
    info "would wait for $HEALTH_URL"
  elif wait_for_http; then
    info "$SERVICE is healthy at $HEALTH_URL"
  else
    warn "not healthy yet — inspect: journalctl -u $SERVICE -n 60"
  fi
else
  info "no build yet — next: sudo ./deploy/deploy.sh   # deps → build → start → verify"
fi

if [[ "$CADDY" == 1 ]]; then
  step "Installing Caddyfile"
  if ! command -v caddy >/dev/null 2>&1; then
    echo "error: caddy not found — install it with ./setup.sh --caddy (or your package manager)" >&2
    exit 1
  fi
  [[ -f Caddyfile ]] || { echo "error: no Caddyfile — run: bunx ignex ops caddy --domain <domain>" >&2; exit 1; }
  caddy validate --config ./Caddyfile >/dev/null
  if [[ -f /etc/caddy/Caddyfile ]]; then
    run cp -f /etc/caddy/Caddyfile "/etc/caddy/Caddyfile.bak.$(date +%Y%m%d%H%M%S)"
  fi
  run mkdir -p /etc/caddy
  run cp -f ./Caddyfile /etc/caddy/Caddyfile
  run systemctl enable caddy
  if systemctl is-active --quiet caddy; then run systemctl reload caddy; else run systemctl restart caddy; fi
  info "certificate for ${domain} is issued automatically on first HTTPS request"
  warn "make sure DNS (A/AAAA for ${domain}) points at this host"
fi
`;
}
