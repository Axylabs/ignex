/**
 * @fileoverview `ignex ops systemd` templates — hardened systemd units, a
 * health-gated deploy script and a production env template for running a
 * built ignex server as a system service behind a TLS-terminating proxy:
 *
 *   <name>.service          the app unit (SIGTERM drain, sandboxing, loopback)
 *   <name>-infra.service    oneshot: bring the compose stack up at boot
 *                           (`--with-infra`; `docker compose up -d --wait` is
 *                           what makes the app unit safe to start after it —
 *                           it blocks until every service is healthy)
 *   deploy/deploy.sh        sudo deploy: deps → infra → build → migrate →
 *                           restart → health poll → rollback on failure
 *   deploy/env.production.example   HOST=127.0.0.1, HTTPS=false (proxy
 *                                   terminates TLS), PUBLIC_BASE_URL
 *
 * Pure functions, string in → string out (same convention as `ops-*.ts`).
 */

export interface SystemdUnitOptions {
  /** Service/unit name — also the StateDirectory and default User. */
  name: string;
  /** The system user the service runs as (default: the unit name). */
  user: string;
  /** Absolute path of the deployed checkout (WorkingDirectory). */
  appDir: string;
  /** Absolute bun binary path on the target host (default /usr/local/bin/bun). */
  bunPath: string;
}

/**
 * The app unit. Contract notes carried over from production use:
 * - `TimeoutStopSec=20s` — the server drains in-flight requests on SIGTERM
 *   with a 10s deadline, then exits (0 = drained, 1 = deadline hit); give it
 *   headroom before systemd sends SIGKILL.
 * - `ProtectSystem=strict` + `ReadWritePaths=.ignex` — the compiled server
 *   flushes hot-route heat there; everything else stays read-only.
 * - No hard dependency on infra: the app boots lazily and answers `/health`
 *   while dependencies are down, so a broken DB never wedges the unit.
 */
export function systemdUnitTemplate(options: SystemdUnitOptions): string {
  const { name, user, appDir, bunPath } = options;
  return `# ${name}.service — generated by \`ignex ops systemd\`.
#
# Runs the compiled server (bun .ignex/server.js) on loopback; TLS terminates
# at your proxy (\`ignex ops caddy\`). The app reads .env from the working
# directory — production values belong in deploy/env.production.example.
#
# Install (see deploy/README or the generator output):
#   sudo cp ${name}.service /etc/systemd/system/
#   sudo systemctl daemon-reload && sudo systemctl enable --now ${name}

[Unit]
Description=${name} (ignex API server)
Documentation=file://${appDir}/README.md
Wants=network-online.target
After=network-online.target

[Service]
Type=simple
User=${user}
Group=${user}
WorkingDirectory=${appDir}
Environment=NODE_ENV=production
Environment=IGNEX_HTTPS=0
Environment=HOME=/var/lib/${name}
ExecStart=${bunPath} .ignex/server.js
Restart=on-failure
RestartSec=3s
# On SIGTERM the server drains in-flight requests with a 10s deadline, then
# exits (0 = drained, 1 = deadline hit). Give it headroom before SIGKILL.
KillSignal=SIGTERM
TimeoutStopSec=20s
LimitNOFILE=65536

# Hardening — the process only needs to read the checkout and write .ignex/
# (hot-route heat flush) plus its state dir.
NoNewPrivileges=true
PrivateTmp=true
ProtectSystem=strict
ReadWritePaths=-${appDir}/.ignex
StateDirectory=${name}
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true
RestrictSUIDSGID=true
RestrictRealtime=true
LockPersonality=true

[Install]
WantedBy=multi-user.target
`;
}

export interface SystemdInfraUnitOptions {
  /** Service/unit name — the infra unit is `<name>-infra`. */
  name: string;
  /** Working directory holding the compose file. */
  workDir: string;
  /** Path to the compose file (absolute; passed via -f). */
  composeFile: string;
}

/**
 * Oneshot unit that brings the compose stack up at boot. `up -d --wait` is
 * the load-bearing part: it blocks until every service is healthy (or runs),
 * which is what makes the app unit safe to start after this one on a fresh
 * boot — no app-specific readiness script needed.
 */
export function systemdInfraUnitTemplate(options: SystemdInfraUnitOptions): string {
  const { name, workDir, composeFile } = options;
  return `# ${name}-infra.service — generated by \`ignex ops systemd --with-infra\`.
#
# Brings the compose stack up at boot and waits for health. Deploys do NOT
# restart this unit (that would stop the database); they run the same
# \`docker compose up -d --wait\` directly (deploy/deploy.sh does).
#
# Install:
#   sudo cp ${name}-infra.service /etc/systemd/system/
#   sudo systemctl daemon-reload && sudo systemctl enable ${name}-infra
#
# Then make the app unit start after it — add to ${name}.service [Unit]:
#   Wants=${name}-infra.service
#   After=${name}-infra.service

[Unit]
Description=${name} infra (docker compose)
Documentation=file://${workDir}/README.md
Requires=docker.service
After=docker.service network-online.target
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=true
WorkingDirectory=${workDir}
ExecStart=docker compose -f ${composeFile} up -d --wait
TimeoutStartSec=600s

[Install]
WantedBy=multi-user.target
`;
}

export interface SystemdDeployOptions {
  /** Service/unit name. */
  name: string;
  /** Absolute path of the deployed checkout. */
  appDir: string;
  /** Absolute bun binary path on the target host. */
  bunPath: string;
  /** The system user the service runs as. */
  user: string;
  /** Local port the app serves on (health polling). */
  port: number;
  /** Liveness path polled after restart (framework contract: /health). */
  healthPath: string;
  /** Include the compose-infra step (`docker compose up -d --wait`). */
  withInfra: boolean;
  /** Compose file path (when {@linkcode withInfra}). */
  composeFile: string;
  /** Include a `bun run db:migrate` step (additive-first projects). */
  migrate: boolean;
}

/**
 * The sudo deploy script: pull → install → infra → (migrate) → build →
 * restart → poll → rollback to the previous artifact when the new build does
 * not come up healthy. Re-runnable at any time; `--dry-run` prints every
 * mutation first.
 */
export function systemdDeployTemplate(options: SystemdDeployOptions): string {
  const { name, appDir, bunPath, user, port, healthPath, withInfra, composeFile, migrate } =
    options;
  const infraBlock = withInfra
    ? `  step "Starting infra (compose up -d --wait)"
  run docker compose -f ${composeFile} up -d --wait
`
    : "";
  const migrateBlock = migrate
    ? `if [[ "$SKIP_MIGRATE" == 0 ]]; then
  step "Applying migrations (bun run db:migrate)"
  run runuser -u ${user} -- ${bunPath} run db:migrate
fi
`
    : "";
  return `#!/usr/bin/env bash
# deploy.sh — (re)deploy ${name} on this host. Generated by \`ignex ops systemd\`.
#
#   sudo deploy/deploy.sh              # install → build → restart → verify
#   sudo deploy/deploy.sh --pull       # git pull --ff-only first
#
# Re-runnable at any time. A build that does not come up healthy is rolled
# back to the previous artifact (migrations are additive-first, so the old
# build keeps working against the new schema).
set -euo pipefail

APP_DIR="${appDir}"
SERVICE="${name}"
BUN="${bunPath}"
APP_USER="${user}"
HEALTH_URL="http://127.0.0.1:${port}${healthPath}"
PULL=0 SKIP_MIGRATE=0 NO_RESTART=0 DRY_RUN=0

while [[ $# -gt 0 ]]; do
  case "$1" in
    --pull) PULL=1 ;;
    --skip-migrate) SKIP_MIGRATE=1 ;;
    --no-restart) NO_RESTART=1 ;;
    --dry-run) DRY_RUN=1 ;;
    -h|--help) grep '^#' "$0" | head -n 8; exit 0 ;;
    *) echo "unknown option: $1" >&2; exit 1 ;;
  esac
  shift
done

require_root() { [[ "$(id -u)" == 0 ]] || { echo "error: run with sudo" >&2; exit 1; }; }
run() {
  if [[ "$DRY_RUN" == 1 ]]; then printf '    + %s\\n' "$*"; return 0; fi
  "$@"
}
step() { printf '\\n==> %s\\n' "$*"; }
info() { printf '    %s\\n' "$*"; }
wait_for_http() {
  local start=$SECONDS
  while :; do
    if curl -fsS --max-time 5 "$HEALTH_URL" >/dev/null 2>&1; then return 0; fi
    if (( SECONDS - start >= 60 )); then return 1; fi
    sleep 2
  done
}
rollback() {
  warn() { printf '    warning: %s\\n' "$*" >&2; }
  warn "the new build did not come up — recent log:"
  journalctl -u "$SERVICE" -n 60 --no-pager || true
  if [[ -f "$APP_DIR/.ignex/server.js.prev" ]]; then
    step "Rolling back to the previous build"
    runuser -u "$APP_USER" -- mv -f "$APP_DIR/.ignex/server.js.prev" "$APP_DIR/.ignex/server.js"
    systemctl restart "$SERVICE"
    if wait_for_http; then warn "rolled back — fix the problem and redeploy"; else warn "rollback also unhealthy — inspect journalctl -u $SERVICE"; fi
  else
    warn "no previous build to roll back to"
  fi
  exit 1
}

require_root
cd "$APP_DIR"

step "Preflight — $APP_DIR"
[[ -x "$BUN" ]] || { echo "error: bun not found at $BUN" >&2; exit 1; }
if [[ ! -f .env ]]; then
  echo "warning: no .env — production values go there (see deploy/env.production.example)"
fi
info "revision $(git -c safe.directory='*' -C "$APP_DIR" rev-parse --short HEAD 2>/dev/null || echo unknown)"
if [[ "$DRY_RUN" == 1 ]]; then echo "    (dry run — nothing will be changed)"; fi

if [[ "$PULL" == 1 ]]; then
  step "Pulling latest (git pull --ff-only)"
  run runuser -u "$APP_USER" -- git -C "$APP_DIR" pull --ff-only
fi

step "Installing dependencies (bun install --frozen-lockfile)"
run runuser -u "$APP_USER" -- ${bunPath} install --frozen-lockfile
${infraBlock}${migrateBlock}step "Building the production artifact (bun run build)"
if [[ -f .ignex/server.js ]]; then
  run runuser -u "$APP_USER" -- cp -f .ignex/server.js .ignex/server.js.prev
fi
run runuser -u "$APP_USER" -- env HTTPS=false IGNEX_HTTPS=0 NODE_ENV=production ${bunPath} run build

if [[ "$NO_RESTART" == 1 ]]; then
  info "--no-restart: restart $SERVICE when ready (systemctl restart $SERVICE)"
  exit 0
fi

step "Restarting $SERVICE"
run systemctl restart "$SERVICE"
if [[ "$DRY_RUN" == 1 ]]; then
  info "would wait for $HEALTH_URL"
  exit 0
fi
step "Verifying ($HEALTH_URL)"
wait_for_http || rollback
info "deployed $(git -c safe.directory='*' -C "$APP_DIR" rev-parse --short HEAD 2>/dev/null || echo unknown) — $SERVICE is healthy"
runuser -u "$APP_USER" -- rm -f "$APP_DIR/.ignex/server.js.prev"
`;
}

export interface EnvProductionOptions {
  /** Public origin used in emails/links; rendered as the placeholder default. */
  publicBaseUrl: string;
}

/**
 * Production env template for a host-run (systemd) deployment behind a
 * TLS-terminating proxy: loopback bind, HTTPS off, NODE_ENV=production.
 */
export function envProductionTemplate(options: EnvProductionOptions): string {
  return `# Production environment — copy to .env at the deployed checkout and adjust.
# Mode 600, owned by the service user; NEVER commit real values.
# TLS terminates at your proxy (ignex ops caddy) — the app serves plain HTTP
# on loopback only.

NODE_ENV=production

# Loopback only — the proxy is the sole public entrypoint.
HOST=127.0.0.1
PORT=3000

# The production build never generates certificates; it serves HTTP/1.1 for
# the proxy. (IGNEX_HTTPS=0 is also set by the systemd unit as a backstop.)
HTTPS=false

# Public origin used in emails/links — must be the real https origin.
PUBLIC_BASE_URL=${options.publicBaseUrl}
`;
}
