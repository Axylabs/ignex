/**
 * Tests for `utils/env-fill` — the pure env-file line patcher (parse /
 * unfilled / apply), the secret-var discovery (schema import + source-scan
 * fallback), and the IO wrapper `fillEnvSecrets`.
 */

import { existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { describe, expect, it } from "vitest";
import {
  applySecrets,
  fillEnvSecrets,
  listSecretVars,
  parseEnvAssignments,
  scanSecretVars,
  unfilledSecretKeys,
} from "../src/utils/env-fill.js";

/** Create a throwaway project dir for one test. */
function tmpProject(): string {
  const dir = join(tmpdir(), `ignex-cli-envfill-${Math.random().toString(36).slice(2)}`);
  mkdirSync(dir, { recursive: true });
  return dir;
}

/** The scaffold's canonical env module source (secret declaration included). */
const SCAFFOLD_ENV_TS = `import { Type, defineEnv } from "@ignex/core/env";

export const envSchema = Type.Object({
  NODE_ENV: Type.String({ default: "development" }),
  PORT: Type.Integer({ default: 3000 }),
  SESSION_SECRET: Type.Optional(Type.String({ metadata: { secret: true } })),
});

export const env = defineEnv(envSchema);
`;

describe("parseEnvAssignments", () => {
  it("maps KEY=value lines, later wins, comments ignored", () => {
    const map = parseEnvAssignments([
      "# SESSION_SECRET=placeholder",
      "A=1",
      "A=2",
      "  B = spaced ",
      "export C=3",
      "# D=commented",
    ]);
    expect(map.get("A")).toBe("2");
    expect(map.get("B")).toBe("spaced");
    expect(map.get("C")).toBe("3");
    expect(map.has("D")).toBe(false);
  });
});

describe("unfilledSecretKeys", () => {
  it("flags missing, empty, quoted-empty, and commented-placeholder keys", () => {
    const lines = ["SESSION_SECRET=", 'OTHER=""', "# COMMENTED=", "SET=yes"];
    const missing = unfilledSecretKeys(lines, [
      "SESSION_SECRET",
      "OTHER",
      "COMMENTED",
      "SET",
      "ABSENT",
    ]);
    expect(missing.sort()).toEqual(["ABSENT", "COMMENTED", "OTHER", "SESSION_SECRET"]);
  });
});

describe("applySecrets", () => {
  it("fills an empty value in place and keeps non-empty ones", () => {
    const result = applySecrets(
      ["A=", "B=keepme"],
      [
        { key: "A", value: "gen-a" },
        { key: "B", value: "gen-b" },
      ],
    );
    expect(result.lines).toEqual(["A=gen-a", "B=keepme"]);
    expect(result.filled).toEqual(["A"]);
    expect(result.kept).toEqual(["B"]);
  });

  it("uncomments a commented placeholder from the ops templates", () => {
    const result = applySecrets(
      ["# SESSION_SECRET=", "PORT=3000"],
      [{ key: "SESSION_SECRET", value: "gen" }],
    );
    expect(result.lines).toEqual(["SESSION_SECRET=gen", "PORT=3000"]);
    expect(result.filled).toEqual(["SESSION_SECRET"]);
  });

  it("appends absent keys under the generated marker, once", () => {
    const result = applySecrets(
      ["PORT=3000", ""],
      [
        { key: "A", value: "a" },
        { key: "B", value: "b" },
      ],
    );
    const joined = result.lines.join("\n");
    expect(joined).toContain("# generated by ignex");
    expect(joined.match(/# generated by ignex/g)?.length).toBe(1);
    expect(joined).toContain("A=a");
    expect(joined).toContain("B=b");
    expect(result.filled).toEqual(["A", "B"]);
  });

  it("patches only the LAST occurrence of a repeated key", () => {
    const result = applySecrets(["A=", "A="], [{ key: "A", value: "gen" }]);
    expect(result.lines).toEqual(["A=", "A=gen"]);
  });
});

describe("scanSecretVars (source-scan fallback)", () => {
  it("finds canonical secret declarations, in order, deduped", () => {
    const names = scanSecretVars(SCAFFOLD_ENV_TS);
    expect(names).toEqual(["SESSION_SECRET"]);
  });

  it("ignores non-secret properties", () => {
    expect(scanSecretVars("const x = Type.String();")).toEqual([]);
  });
});

describe("listSecretVars", () => {
  it("returns [] without an env module", async () => {
    const root = tmpProject();
    try {
      expect(await listSecretVars(root)).toEqual([]);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("falls back to source scan when the module cannot be imported", async () => {
    const root = tmpProject();
    // The scaffold source imports @ignex/core/env which does not resolve from
    // the OS temp dir — exercising the fallback path by construction.
    mkdirSync(join(root, "src", "config"), { recursive: true });
    writeFileSync(join(root, "src", "config", "env.ts"), SCAFFOLD_ENV_TS);
    try {
      expect(await listSecretVars(root)).toEqual(["SESSION_SECRET"]);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});

describe("fillEnvSecrets", () => {
  it("generates values for declared secrets, never overwriting set ones", async () => {
    const root = tmpProject();
    mkdirSync(join(root, "src", "config"), { recursive: true });
    writeFileSync(join(root, "src", "config", "env.ts"), SCAFFOLD_ENV_TS);
    writeFileSync(join(root, ".env"), "SESSION_SECRET=\nOTHER=stays\n");
    try {
      const fill = await fillEnvSecrets(root, ".env", () => "generated-value");
      expect(fill?.filled).toEqual(["SESSION_SECRET"]);
      const env = readFileSync(join(root, ".env"), "utf8");
      expect(env).toContain("SESSION_SECRET=generated-value");
      expect(env).toContain("OTHER=stays");
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("returns null when the env file is absent and creates nothing", async () => {
    const root = tmpProject();
    mkdirSync(join(root, "src", "config"), { recursive: true });
    writeFileSync(join(root, "src", "config", "env.ts"), SCAFFOLD_ENV_TS);
    try {
      expect(await fillEnvSecrets(root, ".env")).toBeNull();
      expect(existsSync(join(root, ".env"))).toBe(false);
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });

  it("reports kept keys when everything is already set", async () => {
    const root = tmpProject();
    mkdirSync(join(root, "src", "config"), { recursive: true });
    writeFileSync(join(root, "src", "config", "env.ts"), SCAFFOLD_ENV_TS);
    writeFileSync(join(root, ".env"), "SESSION_SECRET=already-here\n");
    try {
      const fill = await fillEnvSecrets(root, ".env", () => "new");
      expect(fill?.filled).toEqual([]);
      expect(fill?.kept).toEqual(["SESSION_SECRET"]);
      expect(readFileSync(join(root, ".env"), "utf8")).toContain("already-here");
    } finally {
      rmSync(root, { recursive: true, force: true });
    }
  });
});
