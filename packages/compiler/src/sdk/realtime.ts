/** Deterministic file ordering for the emitted package. */
const byPath = (a: SdkFile, b: SdkFile): number => (a.path < b.path ? -1 : a.path > b.path ? 1 : 0);

/**
 * Assemble the realtime package files: the generated nova stack plus the
 * framework-owned schema/payloads/client/rpc/barrel modules.
 */
const emitRealtimeFiles = async (ctx: SdkGenerateContext): Promise<readonly SdkFile[]> => {
  const input = requireRealtimeInput(ctx);

  const nova = await loadNovaGenerate();
  const generated = nova.generateBindings(
    {
      ...(input.schemas !== undefined ? { schemas: input.schemas } : {}),
      events: input.events,
      ...(input.controlEvents !== undefined ? { controlEvents: input.controlEvents } : {}),
    },
    { rust: false, ffiMode: "optional", subjectPrefix: input.subjectPrefix, force: true },
  );

  const files: SdkFile[] = [];
  for (const [rel, content] of Object.entries(generated.files)) {
    if (rel.startsWith("rust/") || rel === "README.md") continue;
    files.push({ path: packagePathOf(rel), content });
  }
  files.push(
    { path: "package.json", content: emitPackageJson(ctx) },
    { path: "README.md", content: emitReadme(ctx) },
    { path: "realtime/schema.ts", content: emitSchemaTs(input) },
    { path: "realtime/payloads.gen.ts", content: emitPayloadsGen(input) },
    { path: "realtime/client.gen.ts", content: emitClientGen() },
    { path: "realtime/server.ts", content: emitServerFacade() },
    { path: "realtime/rpc.gen.ts", content: emitRpcGen() },
    { path: "realtime/index.ts", content: emitIndexTs() },
  );
  return [...files].sort(byPath);
};

/**
 * The realtime SDK platform: emits an installable npm package carrying the
 * nova FlatBuffer wire stack, a typed WebSocket client and typed RPC calls,
 * derived from the app's realtime build artifacts.
 */
export const realtimePlatform: SdkPlatform = {
  id: "realtime",
  label: "Realtime",
  description:
    "npm package: nova FlatBuffer wire stack + typed WebSocket client + typed RPC-over-WS (from realtime.json / rpc-manifest.json).",
  generate(ctx: SdkGenerateContext): Promise<readonly SdkFile[]> {
    return emitRealtimeFiles(ctx);
  },
};
