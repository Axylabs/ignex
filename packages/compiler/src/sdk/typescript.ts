/**
 * @fileoverview TypeScript SDK platform.
 *
 * Emits a complete, self-contained npm package for frontend consumers:
 *
 * - `dist/client.js` — a zero-dependency ESM fetch client (no `@ignex/*`
 *   imports, works in browsers / Node / Bun), with per-route call shapes
 *   baked in at generation time.
 * - `dist/types.d.ts` — concrete request/params/query/response types derived
 *   from the OpenAPI schemas (via the JSON Schema → TS emitter).
 * - `dist/routes.d.ts` — the typed `IgnexRoutes` route map + `IgnexClient`
 *   contract (same DX as the compiler-generated client, self-contained).
 * - `openapi.json`, `package.json`, `README.md` — installable + documented.
 *
 * The platform is pure: {@link generateTypeScriptPlatform} returns
 * {@link SdkFile}s from the shared {@link SdkGenerateContext}.
 */

import { jsonSchemaToTs } from "./json-schema-to-ts";
import type { SdkFile, SdkGenerateContext, SdkPlatform, SdkRouteInfo } from "./types";

/** Path/name sanitizer: `/api/orders-ack` → `ApiOrdersAck`. */
export const pathToName = (path: string): string =>
  path
    .split("/")
    .filter(Boolean)
    .map((segment) => {
      const cleaned = segment.replace(/[^A-Za-z0-9]/g, "");
      return cleaned === "" ? "Route" : cleaned.charAt(0).toUpperCase() + cleaned.slice(1);
    })
    .join("");

/** Whether the route's call shape carries path params. */
export const hasParams = (route: SdkRouteInfo): boolean =>
  route.paramNames.length > 0 || route.paramsSchema !== undefined;

/** Whether the route exposes query typing (schema or handler usage). */
export const hasQuery = (route: SdkRouteInfo): boolean =>
  route.usesQuery || route.querySchema !== undefined;

/**
 * Deterministic per-part type names shared by every emitted file.
 *
 * Names are reserved once, in a canonical order (routes sorted by path, parts
 * in a fixed order), so `types.d.ts` and `routes.d.ts` always reference the
 * same identifiers — even when two route paths sanitize to the same name.
 */
class TypeNameRegistry {
  private readonly names = new Map<string, string>();
  private readonly used = new Set<string>();

  /** Reserve (or return the already-reserved) name for a route part. */
  reserve(prefix: "Params" | "Query" | "Body" | "Response", route: SdkRouteInfo): string {
    const key = `${prefix}|${route.method}|${route.path}`;
    const existing = this.names.get(key);
    if (existing !== undefined) return existing;
    const base = `${prefix}_${route.method.charAt(0)}${route.method.slice(1).toLowerCase()}${pathToName(route.path)}`;
    let name = base;
    let n = 2;
    while (this.used.has(name)) {
      name = `${base}_${n}`;
      n += 1;
    }
    this.used.add(name);
    this.names.set(key, name);
    return name;
  }
}

/** Fallback params type when no params schema exists (mirrors the compiler). */
const paramsTypeFromNames = (names: readonly string[]): string => {
  if (names.length === 0) return "Record<string, never>";
  return `{\n${names.map((name) => `    ${name}: string;`).join("\n")}\n  }`;
};

/** `IgnexRoutes` entry for one route. */
const routeEntry = (route: SdkRouteInfo, names: TypeNameRegistry): string => {
  const method = route.method.toLowerCase();
  const lines: string[] = [`    ${method}: {`];

  if (hasParams(route)) {
    lines.push(`      params: ${names.reserve("Params", route)};`);
  }
  if (hasQuery(route)) {
    lines.push(`      query: ${names.reserve("Query", route)};`);
  }
  if (route.usesBody) {
    lines.push(`      body: ${names.reserve("Body", route)};`);
  }
  lines.push(`      response: ${names.reserve("Response", route)};`);
  lines.push("    };");

  return lines.join("\n");
};

/** Emit `dist/types.d.ts` — named, importable types per route part. */
export const emitTypesDts = (routes: readonly SdkRouteInfo[], ctx: SdkGenerateContext): string => {
  const resolveRef = (ref: string): unknown => {
    if (!ref.startsWith("#/")) return undefined;
    const parts = ref.slice(2).split("/");
    let node: unknown = ctx.openapi;
    for (const part of parts) {
      if (!isRecord(node)) return undefined;
      node = node[part];
    }
    return node;
  };

  const names = new TypeNameRegistry();
  const lines = [
    "// Auto-generated by Ignex SDK generator. Do not edit.",
    "",
    "// Concrete request/response types derived from the compiled OpenAPI document.",
    "",
  ];

  for (const route of routes) {
    if (route.paramsSchema !== undefined) {
      lines.push(
        `export type ${names.reserve("Params", route)} = ${jsonSchemaToTs(route.paramsSchema, { resolveRef })};`,
      );
    } else if (hasParams(route)) {
      lines.push(
        `export type ${names.reserve("Params", route)} = ${paramsTypeFromNames(route.paramNames)};`,
      );
    }

    if (route.querySchema !== undefined) {
      lines.push(
        `export type ${names.reserve("Query", route)} = ${jsonSchemaToTs(route.querySchema, { resolveRef })};`,
      );
    } else if (hasQuery(route)) {
      lines.push(
        `export type ${names.reserve("Query", route)} = Record<string, string | string[]>;`,
      );
    }

    if (route.bodySchema !== undefined) {
      lines.push(
        `export type ${names.reserve("Body", route)} = ${jsonSchemaToTs(route.bodySchema, { resolveRef })};`,
      );
    }

    lines.push(
      route.responseSchema !== undefined
        ? `export type ${names.reserve("Response", route)} = ${jsonSchemaToTs(route.responseSchema, { resolveRef })};`
        : `export type ${names.reserve("Response", route)} = unknown;`,
    );
    lines.push("");
  }

  return lines.join("\n");
};

/** Emit `dist/routes.d.ts` — the typed route map + client contract. */
export const emitRoutesDts = (
  routes: readonly SdkRouteInfo[],
  _ctx: SdkGenerateContext,
): string => {
  const names = new TypeNameRegistry();
  const imports = new Set<string>();

  for (const route of routes) {
    if (hasParams(route)) imports.add(names.reserve("Params", route));
    if (hasQuery(route)) imports.add(names.reserve("Query", route));
    if (route.usesBody) imports.add(names.reserve("Body", route));
    imports.add(names.reserve("Response", route));
  }

  const importLines = [...imports].map((name) => `  ${name},`).join("\n");

  const byPath = new Map<string, SdkRouteInfo[]>();
  for (const route of routes) {
    const group = byPath.get(route.path) ?? [];
    group.push(route);
    byPath.set(route.path, group);
  }

  const pathBlocks: string[] = [];
  for (const [path, group] of byPath) {
    const entries = group.map((route) => routeEntry(route, names)).join("\n");
    pathBlocks.push(`  ${JSON.stringify(path)}: {\n${entries}\n  };`);
  }

  return `// Auto-generated by Ignex SDK generator. Do not edit.
import type {
${importLines}
} from "./types";

// Per-route call signature, derived from the route's declared params/query/body:
//   params+query+body → (params, query, body, init?)
//   params+query      → (params, query, init?)
//   query+body        → (query, body, init?)
//   params+body       → (params, body, init?)
//   params            → (params, init?)
//   query             → (query, init?)
//   body              → (body, init?)
//   none              → (init?)
type IgnexRouteHandler<Route> =
  Route extends { params: infer P; query: infer Q; body: unknown }
    ? (params: P, query: Q, body: unknown, init?: RequestInit) => Promise<unknown>
    : Route extends { params: infer P; query: infer Q }
      ? (params: P, query: Q, init?: RequestInit) => Promise<unknown>
      : Route extends { query: infer Q; body: unknown }
        ? (query: Q, body: unknown, init?: RequestInit) => Promise<unknown>
        : Route extends { params: infer P; body: unknown }
          ? (params: P, body: unknown, init?: RequestInit) => Promise<unknown>
          : Route extends { params: infer P }
            ? (params: P, init?: RequestInit) => Promise<unknown>
            : Route extends { query: infer Q }
              ? (query: Q, init?: RequestInit) => Promise<unknown>
              : Route extends { body: unknown }
                ? (body: unknown, init?: RequestInit) => Promise<unknown>
                : (init?: RequestInit) => Promise<unknown>;

export type IgnexRoutes = {
${pathBlocks.join("\n")}
};

export type IgnexClient = {
  [Path in keyof IgnexRoutes]: {
    [Method in keyof IgnexRoutes[Path]]: IgnexRouteHandler<IgnexRoutes[Path][Method]>;
  };
};
`;
};

