/** Emit `dist/client.js` — the self-contained runtime client. */
type CallShape =
  | "none"
  | "params"
  | "body"
  | "params+body"
  | "query"
  | "params+query"
  | "query+body"
  | "params+query+body";

const emitClientJs = (routes: readonly SdkRouteInfo[]): string => {
  const routeEntries = routes
    .map(
      (r) =>
        `  ${JSON.stringify(`${r.method.toLowerCase()} ${r.path}`)}: ${JSON.stringify(r.path)},`,
    )
    .join("\n");

  const modeFor = (r: SdkRouteInfo): CallShape => {
    const params = hasParams(r);
    const query = hasQuery(r);
    const body = r.usesBody;
    const key = `${params ? "p" : ""}${query ? "q" : ""}${body ? "b" : ""}`;
    const map: Record<string, CallShape> = {
      p: "params",
      pq: "params+query",
      pb: "params+body",
      pqb: "params+query+body",
      q: "query",
      qb: "query+body",
      b: "body",
      "": "none",
    };
    return map[key] ?? "none";
  };

  // Keyed by the full "method path" (same key shape as ROUTES) — a bare path
  // collides when the same route template serves multiple methods with
  // different shapes (e.g. DELETE /gigs/:id = params vs PATCH = params+body).
  const argsEntries = routes
    .map(
      (r) =>
        `  ${JSON.stringify(`${r.method.toLowerCase()} ${r.path}`)}: ${JSON.stringify(modeFor(r))},`,
    )
    .join("\n");

  return `// Auto-generated by Ignex SDK generator. Do not edit.
// Self-contained typed client — no runtime dependencies.

export class ApiClientError extends Error {
  constructor(status, message, body, response) {
    super(message);
    this.name = "ApiClientError";
    this.status = status;
    this.body = body;
    this.response = response;
  }
}

const ROUTES = {
${routeEntries}
};

// Route template → call shape ("none" | "params" | "body" | "params+body" |
// "query" | "params+query" | "query+body" | "params+query+body").
const ROUTE_ARGS = {
${argsEntries}
};

const buildUrl = (path, params) => {
  let url = path;
  for (const [key, value] of Object.entries(params ?? {})) {
    url = url
      .replace(\`:\${key}\`, encodeURIComponent(String(value)))
      .replace(\`*\${key}\`, encodeURIComponent(String(value)));
  }
  return url;
};

// Serialize a query object to a "?a=1&b=x" suffix (array values repeat).
const buildQuery = (query) => {
  if (!query) return "";
  const parts = [];
  for (const [key, value] of Object.entries(query)) {
    if (value === undefined || value === null) continue;
    if (Array.isArray(value)) {
      for (const v of value) {
        parts.push(\`\${encodeURIComponent(key)}=\${encodeURIComponent(String(v))}\`);
      }
    } else {
      parts.push(\`\${encodeURIComponent(key)}=\${encodeURIComponent(String(value))}\`);
    }
  }
  return parts.length > 0 ? \`?\${parts.join("&")}\` : "";
};

// Deep-merge per-call init over the client-wide init so a per-call header
// doesn't clobber headers set on createApiClient (shallow spread would).
const mergeInit = (base, per) => {
  const out = { ...base, ...per };
  if (base?.headers && per?.headers) {
    out.headers = { ...base.headers, ...per.headers };
  }
  return out;
};

export const createApiClient = (options) => {
  const base = (options?.baseUrl ?? "").replace(/\\/+$/, "");
  const baseHeaders = options?.headers ?? {};
  const fetcher = options?.fetch ?? globalThis.fetch;
  const credentials = options?.credentials;
  const baseOptions = { headers: baseHeaders };

  const request = async (method, path, body, init) => {
    const isBody = body !== undefined;
    const headers = { ...baseHeaders, ...(init?.headers ?? {}) };
    if (isBody && typeof body !== "string") headers["content-type"] = "application/json";
    const response = await fetcher(base + path, {
      ...(credentials !== undefined ? { credentials } : {}),
      ...init,
      method,
      headers,
      ...(isBody ? { body: typeof body === "string" ? body : JSON.stringify(body) } : {}),
    });
    const text = await response.text();
    let parsed = null;
    if (text) {
      try {
        parsed = JSON.parse(text);
      } catch {
        parsed = text;
      }
    }
    if (!response.ok) {
      throw new ApiClientError(
        response.status,
        \`Request failed: \${response.status} \${response.statusText} \${path}\`,
        parsed,
        response,
      );
    }
    return parsed;
  };

  const routeHandler = (pathKey) => {
    const path = ROUTES[pathKey] ?? pathKey;
    const mode = ROUTE_ARGS[pathKey] ?? "none";
    const callUrl = (params, query) => buildUrl(path, params) + buildQuery(query);
    return new Proxy({}, {
      get(_, methodKey) {
        return async (...args) => {
          if (mode === "params+query+body") {
            const [params, query, body, init] = args;
            return request(methodKey.toUpperCase(), callUrl(params, query), body, mergeInit(baseOptions, init));
          }
          if (mode === "params+query") {
            const [params, query, init] = args;
            return request(methodKey.toUpperCase(), callUrl(params, query), undefined, mergeInit(baseOptions, init));
          }
          if (mode === "query+body") {
            const [query, body, init] = args;
            return request(methodKey.toUpperCase(), callUrl(undefined, query), body, mergeInit(baseOptions, init));
          }
          if (mode === "query") {
            const [query, init] = args;
            return request(methodKey.toUpperCase(), callUrl(undefined, query), undefined, mergeInit(baseOptions, init));
          }
          if (mode === "params+body") {
            const [params, body, init] = args;
            return request(methodKey.toUpperCase(), buildUrl(path, params), body, mergeInit(baseOptions, init));
          }
          if (mode === "params") {
            const [params, init] = args;
            return request(methodKey.toUpperCase(), buildUrl(path, params), undefined, mergeInit(baseOptions, init));
          }
          if (mode === "body") {
            const [body, init] = args;
            return request(methodKey.toUpperCase(), path, body, mergeInit(baseOptions, init));
          }
          const [init] = args;
          return request(methodKey.toUpperCase(), path, undefined, mergeInit(baseOptions, init));
        };
      },
    });
  };

  return new Proxy({}, {
    get(_, pathKey) {
      return routeHandler(pathKey);
    },
  });
};
`;
};

