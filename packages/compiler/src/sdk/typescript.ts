/** Emit the SDK `package.json`. */
const emitPackageJson = (ctx: SdkGenerateContext): string => {
  const { options } = ctx;
  const name = options.name ?? defaultPackageName(ctx);
  const version = options.version ?? "0.0.0";
  const description =
    options.description ??
    `Generated TypeScript SDK for the \`${ctx.serviceName}\` API (self-contained, zero-dependency typed client).`;
  const pkg = {
    name,
    version,
    description,
    type: "module",
    sideEffects: false,
    main: "./dist/index.js",
    module: "./dist/index.js",
    types: "./dist/index.d.ts",
    exports: {
      ".": {
        types: "./dist/index.d.ts",
        import: "./dist/index.js",
      },
      "./openapi.json": "./openapi.json",
    },
    files: ["dist", "openapi.json", "README.md"],
    license: options.license ?? "MIT",
    engines: { node: ">=18" },
    ...(options.repoUrl !== undefined ? { repository: { type: "git", url: options.repoUrl } } : {}),
  };
  return `${JSON.stringify(pkg, null, 2)}\n`;
};

/** Default package name: `<scope>/<serviceName>-sdk`. */
const defaultPackageName = (ctx: SdkGenerateContext): string => {
  const base = `${ctx.serviceName}-sdk`;
  return ctx.options.scope !== undefined ? `${ctx.options.scope}/${base}` : base;
};

