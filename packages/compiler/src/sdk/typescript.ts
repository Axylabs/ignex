const isRecord = (value: unknown): value is Record<string, unknown> =>
  typeof value === "object" && value !== null && !Array.isArray(value);

/**
 * The TypeScript SDK platform: emits a self-contained, installable npm
 * package with a typed zero-dependency client for the compiled routes.
 */
export const typescriptPlatform: SdkPlatform = {
  id: "typescript",
  label: "TypeScript",
  description:
    "Self-contained npm package: typed zero-dependency ESM client + .d.ts types + openapi.json.",
  generate(ctx: SdkGenerateContext): readonly SdkFile[] {
    const { routes } = ctx;
    const files: SdkFile[] = [
      {
        path: "package.json",
        content: emitPackageJson(ctx),
      },
      {
        path: "README.md",
        content: emitReadme(ctx),
      },
      {
        path: "openapi.json",
        content: `${JSON.stringify(ctx.openapi, null, 2)}\n`,
      },
      {
        path: "dist/types.d.ts",
        content: emitTypesDts(routes, ctx),
      },
      {
        path: "dist/routes.d.ts",
        content: emitRoutesDts(routes, ctx),
      },
      {
        path: "dist/client.d.ts",
        content: emitClientDts(),
      },
      {
        path: "dist/client.js",
        content: emitClientJs(routes),
      },
      ...emitIndexFiles(),
    ];
    return files;
  },
};
