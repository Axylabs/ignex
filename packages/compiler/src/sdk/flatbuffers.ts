/** Emit `dist/codec.js` — envelope codec on the official flatbuffers runtime. */
const emitCodecJs = (): string => `// Auto-generated by Ignex SDK generator. Do not edit.
// Envelope codec for schema.fbs, built on the official "flatbuffers" runtime
// (the same runtime @ignex/nova uses for its typed realtime transport).
// Strings are created before startObject (the builder's notNested guard).

import * as flatbuffers from "flatbuffers";

/** pooled builder — each encode clears it (safe because asUint8Array copies). */
let shared = null;
function getBuilder() {
  if (!shared) shared = new flatbuffers.Builder(1024);
  return shared;
}

function jsonOrEmpty(value) {
  if (value === undefined || value === null) return "";
  if (typeof value === "string") return value;
  return JSON.stringify(value);
}

function parseJson(text) {
  if (!text) return undefined;
  try { return JSON.parse(text); } catch (e) { return text; }
}

/// Encode one request envelope. \`params/query/body\` are JSON-able values.
function encodeRequest({ method, path, params, query, body }) {
  const b = getBuilder();
  const sBody = b.createString(jsonOrEmpty(body));
  const sQuery = b.createString(jsonOrEmpty(query));
  const sParams = b.createString(jsonOrEmpty(params));
  const sPath = b.createString(path || "");
  const sMethod = b.createString(method || "");
  b.startObject(5);
  b.addFieldOffset(4, sBody, 0);
  b.addFieldOffset(3, sQuery, 0);
  b.addFieldOffset(2, sParams, 0);
  b.addFieldOffset(1, sPath, 0);
  b.addFieldOffset(0, sMethod, 0);
  const root = b.endObject();
  b.finish(root);
  return b.asUint8Array();
}

/// Decode a request envelope from bytes.
function decodeRequest(bytes) {
  const bb = new flatbuffers.ByteBuffer(bytes);
  const root = bb.readInt32(bb.position()) + bb.position();
  const field = (id) => {
    const o = bb.__offset(root, 4 + id * 2);
    return o === 0 ? null : bb.__string(root + o);
  };
  return {
    method: field(0) || "",
    path: field(1) || "",
    params: parseJson(field(2)),
    query: parseJson(field(3)),
    body: parseJson(field(4)),
  };
}

/// Encode a response envelope.
function encodeResponse({ status, ok, error, bodyJson, traceId }) {
  const b = getBuilder();
  const sTrace = b.createString(traceId || "");
  const sBody = b.createString(bodyJson || "");
  const sError = b.createString(error || "");
  b.startObject(5);
  b.addFieldOffset(4, sTrace, 0);
  b.addFieldOffset(3, sBody, 0);
  b.addFieldOffset(2, sError, 0);
  b.addFieldInt8(1, ok ? 1 : 0, 0);
  b.addFieldInt16(0, status, 0);
  const root = b.endObject();
  b.finish(root);
  return b.asUint8Array();
}

/// Decode a response envelope from bytes.
function decodeResponse(bytes) {
  const bb = new flatbuffers.ByteBuffer(bytes);
  const root = bb.readInt32(bb.position()) + bb.position();
  const field = (id) => {
    const o = bb.__offset(root, 4 + id * 2);
    return o === 0 ? null : bb.__string(root + o);
  };
  const status = (() => {
    const o = bb.__offset(root, 4);
    return o === 0 ? 0 : bb.readUint16(root + o);
  })();
  const ok = (() => {
    const o = bb.__offset(root, 6);
    return o === 0 ? false : bb.readUint8(root + o) !== 0;
  })();
  return {
    status,
    ok,
    error: field(2) || "",
    bodyJson: field(3) || "",
    traceId: field(4) || "",
  };
}

/// Encode the route-inventory table (reflection).
function encodeApiRoutes(routes) {
  const b = getBuilder();
  const metas = routes.map((r) => {
    const sArgs = b.createString(r.args || "none");
    const sPath = b.createString(r.path);
    const sMethod = b.createString(r.method);
    b.startObject(3);
    b.addFieldOffset(2, sArgs, 0);
    b.addFieldOffset(1, sPath, 0);
    b.addFieldOffset(0, sMethod, 0);
    return b.endObject();
  });
  // flatc pattern for a vector of tables:
  b.startVector(4, metas.length, 4);
  for (let i = metas.length - 1; i >= 0; i--) b.addOffset(metas[i]);
  const vec = b.endVector();
  b.startObject(1);
  b.addFieldOffset(0, vec, 0);
  const root = b.endObject();
  b.finish(root);
  return b.asUint8Array();
}

/// Decode the route-inventory table.
function decodeApiRoutes(bytes) {
  const bb = new flatbuffers.ByteBuffer(bytes);
  const root = bb.readInt32(bb.position()) + bb.position();
  const o = bb.__offset(root, 4);
  if (o === 0) return [];
  const vec = root + o;
  const len = bb.__vector_len(vec);
  const out = [];
  for (let i = 0; i < len; i++) {
    const table = bb.__indirect(bb.__vector(vec) + i * 4);
    const field = (id) => {
      const fo = bb.__offset(table, 4 + id * 2);
      return fo === 0 ? null : bb.__string(table + fo);
    };
    out.push({ method: field(0) || "", path: field(1) || "", args: field(2) || "none" });
  }
  return out;
}

export {
  encodeRequest, decodeRequest,
  encodeResponse, decodeResponse,
  encodeApiRoutes, decodeApiRoutes,
};
`;

