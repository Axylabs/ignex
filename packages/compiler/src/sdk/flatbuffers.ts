/**
 * @fileoverview FlatBuffers frontend-client SDK platform.
 *
 * Emits an installable npm package for frontend teams that want **binary**
 * API transport: a real `.fbs` schema describing the wire envelope, a codec
 * built on the official `flatbuffers` runtime (the same runtime the
 * `@ignex/nova` realtime transport uses), and a typed client whose
 * request/response envelopes ride with the `application/x-flatbuffers`
 * content type (JSON fallback included, so the client also works against
 * vanilla JSON endpoints).
 *
 * Why an envelope + JSON strings? The compiled app's payload schemas are
 * arbitrary JSON Schema (not typed FlatBuffers tables), so the *envelope* is
 * the FlatBuffers contract — method, route template and JSON-encoded params /
 * query / body / response ride as string fields — while the payloads stay
 * exactly what the API already produces. The `.fbs` schema ships the route
 * inventory as a reflection table, so any FlatBuffers tooling can introspect
 * the API surface.
 *
 * The package depends on `flatbuffers` (^25.x) — a tiny, dependency-free
 * runtime — and is generated with the same builder/reader patterns as nova's
 * `ts-ser.ts` (strings created before `startObject`, pooled builder, offsets
 * via `__offset`/`__string`).
 */

