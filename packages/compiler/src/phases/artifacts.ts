/**
 * AOT artifact generation:
 * - routes.d.ts
 * - openapi.json
 * - client.d.ts
 * - manifest.json
 */

import { mkdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { DiagnosticCodes, errorMessage } from "../diagnostics";
import type { CompilerContext, CompilerOptions, RouteDef } from "../types";

const writeGuarded = (file: string, content: string, ctx: CompilerContext, label: string): void => {
  try {
    writeFileSync(file, content);
    ctx.logger.info(`Generated ${label}`);
  } catch (error) {
    ctx.diagnostics.error({
      code: DiagnosticCodes.ArtifactWriteFailed,
      message: `Failed to write ${label}: ${errorMessage(error)}`,
      file,
    });
  }
};

const tsParamType = (paramNames: readonly string[]): string => {
  if (paramNames.length === 0) return "Record<string, never>";

  const lines = paramNames.map((name) => `    ${name}: string;`);
  return `{
${lines.join("\n")}
  }`;
};

export const generateRouteTypes = (routes: readonly RouteDef[]): string => {
  const lines: string[] = [];

  lines.push("// Auto-generated by Flux AOT compiler.");
  lines.push("// Do not edit manually.");
  lines.push("");
  lines.push("export interface FluxRoutes {");

  const byPath = new Map<string, RouteDef[]>();
  for (const route of routes) {
    const group = byPath.get(route.path);
    if (group) group.push(route);
    else byPath.set(route.path, [route]);
  }

  for (const [path, defs] of byPath) {
    lines.push(`  ${JSON.stringify(path)}: {`);

    for (const route of defs) {
      const method = route.method.toLowerCase();
      lines.push(`    ${method}: {`);

      if (route.paramNames.length > 0) {
        lines.push(`      params: ${tsParamType(route.paramNames)};`);
      }

      if (route.usage.query) {
        lines.push("      query: Record<string, string | string[]>;");
      }

      if (route.usage.body) {
        lines.push("      body: unknown;");
      }

      lines.push("      response: unknown;");
      lines.push("    };");
    }

    lines.push("  };");
  }

  lines.push("}");
  lines.push("");

  return lines.join("\n");
};

export const generateClientDts = (): string => {
  return `// Auto-generated by Flux AOT compiler.
import type { FluxRoutes } from "./routes";

export type FluxClient = {
  [Path in keyof FluxRoutes]: {
    [Method in keyof FluxRoutes[Path]]: (
      ...args: FluxRoutes[Path][Method] extends { params: infer P }
        ? [params: P, init?: RequestInit]
        : [init?: RequestInit]
    ) => Promise<unknown>;
  };
};

export declare function createApiClient(baseUrl?: string, init?: RequestInit): FluxClient;
`;
};

/**
 * Generate a real typed client implementation (uses `createClient` from
 * `@flux/core` behind a path/method proxy).
 */
export const generateClient = (routes: readonly RouteDef[]): string => {
  const routeEntries = routes
    .filter((r) => r.method !== "ALL")
    .map(
      (r) =>
        `  ${JSON.stringify(`${r.method.toLowerCase()} ${r.path}`)}: ${JSON.stringify(r.path)},`,
    )
    .join("\n");

  return `// Auto-generated by Flux AOT compiler.
import { createClient } from "@flux/core";
import type { FluxRoutes } from "./routes";

export type FluxClient = {
  [Path in keyof FluxRoutes]: {
    [Method in keyof FluxRoutes[Path]]: (
      ...args: FluxRoutes[Path][Method] extends { params: infer P }
        ? [params: P, init?: RequestInit]
        : [init?: RequestInit]
    ) => Promise<unknown>;
  };
};

const ROUTES: Record<string, string> = {
${routeEntries}
};

const buildUrl = (path: string, params?: Record<string, string | number>): string => {
  let url = path;
  for (const [key, value] of Object.entries(params ?? {})) {
    url = url
      .replace(\`:\${key}\`, encodeURIComponent(String(value)))
      .replace(\`*\${key}\`, encodeURIComponent(String(value)));
  }
  return url;
};

export function createApiClient(baseUrl = "", init?: RequestInit): FluxClient {
  const client = createClient({ baseUrl });

  const routeHandler = (pathKey: string) => {
    const path = ROUTES[pathKey] ?? pathKey;
    return new Proxy({} as Record<string, (...args: unknown[]) => Promise<unknown>>, {
      get(_, methodKey: string) {
        return async (...args: unknown[]) => {
          const hasParams =
            args.length >= 1 &&
            typeof args[0] === "object" &&
            args[0] !== null &&
            !(args[0] instanceof Request) &&
            !(args[0] instanceof URLSearchParams);
          const params = hasParams ? (args[0] as Record<string, string>) : undefined;
          const requestInit = hasParams
            ? (args[1] as RequestInit | undefined)
            : (args[0] as RequestInit | undefined);
          return client.request(methodKey.toUpperCase(), buildUrl(path, params), undefined, {
            ...init,
            ...(requestInit ?? {}),
          });
        };
      },
    });
  };

  return new Proxy({} as FluxClient, {
    get(_, pathKey: string) {
      return routeHandler(pathKey);
    },
  });
}
`;
};

const toOpenApiPath = (path: string): string =>
  path.replace(/:([A-Za-z0-9_]+)/g, "{$1}").replace(/\*([A-Za-z0-9_]+)/g, "{$1}");

const stripId = (schema: unknown): unknown => {
  if (schema && typeof schema === "object") {
    const clone = { ...(schema as Record<string, unknown>) };
    delete clone.$id;
    return clone;
  }
  return schema;
};

const isStatusMap = (value: unknown): value is Record<string, unknown> => {
  if (!value || typeof value !== "object") return false;
  const keys = Object.keys(value);
  return keys.length > 0 && keys.every((k) => /^\d{3}$/.test(k));
};

const schemaToParameters = (
  schemaObj: unknown,
  location: "path" | "query" | "header",
  requiredOverride?: readonly string[],
): unknown[] => {
  if (!schemaObj || typeof schemaObj !== "object") return [];
  const schema = schemaObj as { properties?: Record<string, unknown>; required?: string[] };
  if (!schema.properties || typeof schema.properties !== "object") return [];

  const required = new Set(schema.required ?? requiredOverride ?? []);

  return Object.entries(schema.properties).map(([name, propSchema]) => ({
    name,
    in: location,
    required: location === "path" || required.has(name),
    schema: stripId(propSchema),
  }));
};

const statusDescription = (status: string): string => {
  const map: Record<string, string> = {
    "200": "OK",
    "201": "Created",
    "204": "No Content",
    "400": "Bad Request",
    "401": "Unauthorized",
    "403": "Forbidden",
    "404": "Not Found",
    "409": "Conflict",
    "422": "Unprocessable Entity",
    "429": "Too Many Requests",
    "500": "Internal Server Error",
  };
  return map[status] ?? "Response";
};

export const generateOpenApi = (
  routes: readonly RouteDef[],
  opts: CompilerOptions,
): Record<string, unknown> => {
  const paths: Record<string, Record<string, unknown>> = {};

  for (const route of routes) {
    if (route.method === "ALL") continue;

    const openApiPath = toOpenApiPath(route.path);
    paths[openApiPath] ??= {};

    const operation: Record<string, unknown> = {
      operationId: `${route.method.toLowerCase()}_${openApiPath.replace(/[{}/]/g, "_")}`,
      responses: {
        "200": {
          description: "Successful response",
        },
      },
    };

    const detail = (route.config as any)?.detail;
    if (detail && typeof detail === "object") {
      Object.assign(operation, detail);
    }

    const schemaDoc = route.schemaDoc as Record<string, unknown> | undefined;
    const parameters: unknown[] = [];

    if (route.paramNames.length > 0) {
      if (schemaDoc?.params && typeof schemaDoc.params === "object") {
        parameters.push(...schemaToParameters(schemaDoc.params, "path", route.paramNames));
      } else {
        for (const name of route.paramNames) {
          parameters.push({ name, in: "path", required: true, schema: { type: "string" } });
        }
      }
    }

    if (schemaDoc?.query && typeof schemaDoc.query === "object") {
      parameters.push(...schemaToParameters(schemaDoc.query, "query"));
    }

    if (schemaDoc?.headers && typeof schemaDoc.headers === "object") {
      parameters.push(...schemaToParameters(schemaDoc.headers, "header"));
    }

    if (parameters.length > 0) {
      operation.parameters = parameters;
    }

    if (schemaDoc?.body) {
      operation.requestBody = {
        content: {
          "application/json": {
            schema: stripId(schemaDoc.body),
          },
        },
      };
    } else if (route.usage.body) {
      operation.requestBody = {
        content: {
          "application/json": {
            schema: { type: "object" },
          },
        },
      };
    }

    const responseSchema = schemaDoc?.response;
    if (responseSchema) {
      const responses: Record<string, unknown> = {};

      if (isStatusMap(responseSchema)) {
        for (const [status, schema] of Object.entries(responseSchema)) {
          responses[status] = {
            description: statusDescription(status),
            content: { "application/json": { schema: stripId(schema) } },
          };
        }
      } else {
        responses["200"] = {
          description: "Successful response",
          content: { "application/json": { schema: stripId(responseSchema) } },
        };
      }

      operation.responses = responses;
    }

    paths[openApiPath][route.method.toLowerCase()] = operation;
  }

  return {
    openapi: "3.1.0",
    info: {
      title: opts.serviceName ?? "flux",
      version: "1.0.0",
    },
    paths,
  };
};

export const generateManifest = (
  routes: readonly RouteDef[],
  opts: CompilerOptions,
): Record<string, unknown> => ({
  generatedAt: new Date().toISOString(),
  serviceName: opts.serviceName ?? "flux",
  target: opts.target,
  optimizationLevel: opts.optimizationLevel,
  routes: routes.map((r) => ({
    method: r.method,
    path: r.path,
    file: r.file,
    isStatic: r.isStatic,
    isDynamic: r.isDynamic,
    segmentCount: r.segmentCount,
    isConstantResponse: r.isConstantResponse,
    responseType: r.responseType,
    hotnessScore: r.hotnessScore,
    paramNames: r.paramNames,
    hooks: r.hooks,
    usage: r.usage,
  })),
});

export const writeArtifacts = (
  routes: readonly RouteDef[],
  opts: CompilerOptions,
  ctx: CompilerContext,
): void => {
  mkdirSync(opts.outDir, { recursive: true });

  if (opts.generateTypes) {
    const types = generateRouteTypes(routes);
    writeGuarded(join(opts.outDir, "routes.d.ts"), types, ctx, "routes.d.ts");
  }

  if (opts.generateClient) {
    writeGuarded(join(opts.outDir, "client.d.ts"), generateClientDts(), ctx, "client.d.ts");
    writeGuarded(join(opts.outDir, "client.ts"), generateClient(routes), ctx, "client.ts");
  }

  if (opts.generateOpenAPI) {
    const openapi = generateOpenApi(routes, opts);
    writeGuarded(
      join(opts.outDir, "openapi.json"),
      JSON.stringify(openapi, null, 2),
      ctx,
      "openapi.json",
    );
  }

  const manifest = generateManifest(routes, opts);
  writeGuarded(
    join(opts.outDir, "manifest.json"),
    JSON.stringify(manifest, null, 2),
    ctx,
    "manifest.json",
  );
};
